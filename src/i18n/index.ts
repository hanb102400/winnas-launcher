/** 语言代码 → 字典（类型化：缺 key 编译期报错）。 */
const dictionaries: Record<string, Messages> = {
  "zh-CN": zhCN,
  "zh-TW": zhTW,
  en,
  ja,
  ko,
  es,
  ar,
  fr,
  de,
  ru,
};

// ── 当前语言（默认简体中文；App 启动时按 config.language 覆盖） ──
let currentLang: string = (() => {
  try {
    const stored = localStorage.getItem("winnas.lang");
    return stored && dictionaries[stored] ? stored : "zh-CN";
  } catch {
    return "zh-CN";
  }
})();

export function getLang(): string {
  return currentLang;
}

export function setLang(code: string): void {
  if (!dictionaries[code]) return;
  currentLang = code;
  try {
    localStorage.setItem("winnas.lang", code);
  } catch {
    /* 忽略 */
  }
}

/** 取当前语言的文案；支持 `{key}` 占位符替换（如 `t("toastLoaded", { count: 5 })`）。 */
export function t(key: keyof Messages, params?: Record<string, string | number>): string {
  const dict = dictionaries[currentLang] ?? dictionaries["zh-CN"];
  let s = dict[key] ?? dictionaries["zh-CN"][key] ?? String(key);
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      // 不用 replaceAll（需 ES2021），split/join 兼容 ES2020
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}
